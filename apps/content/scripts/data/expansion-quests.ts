const axes: Record<QuestCategory, [Attribute, Attribute]> = {
  exploration: ['exploration', 'vitality'],
  learning: ['growth', 'exploration'],
  creation: ['creativity', 'growth'],
  encounter: ['connection', 'courage'],
  random: ['creativity', 'exploration'],
  special: ['growth', 'creativity'],
};

function quest(
  key: string,
  category: QuestCategory,
  title: string,
  subtitle: string,
  description: string,
  steps: [string, string, string],
  safety: string,
  source: keyof typeof EXPANSION_SOURCES,
) {
  // These are short, low-barrier activities. Multi-stage creative/learning tasks use level 2.
  const difficulty: Difficulty = ['learning', 'creation', 'special'].includes(category) ? 2 : 1;
  const reward = BASE_REWARDS[difficulty];
  const attributes = Object.fromEntries(ATTRIBUTES.map((axis) => [axis, 0]));
  attributes[axes[category][0]] = Math.ceil(reward.attributePoints / 2);
  attributes[axes[category][1]] = Math.floor(reward.attributePoints / 2);
  const outside = category === 'exploration';
  const social = category === 'encounter';
  return {
    key,
    sources: source === 'original' ? [] : [source],
    content: questContentSchema.parse({
      title,
      subtitle,
      description,
      category,
      steps,
      duration: difficulty === 2 ? '15–25 分钟' : '10–15 分钟',
      budget: '0 元（使用已有物品，不要求消费）',
      people: social ? '与一位自愿参与的熟人；先征得同意' : '独自或与熟人一起',
      indoorOutdoor: outside ? '户外或开放公共室内；按步骤选择合适地点' : '室内可做',
      timeOfDay: outside ? '白天、天气适宜且场所开放时' : '方便且不打扰他人时',
      environment: outside
        ? '熟悉、合法开放且可安全停留的区域；无合适地点可换任务'
        : '安全安静的室内，可坐着完成',
      preparation:
        '先查看步骤中的物品与场地要求；使用已有纸笔、书籍或设备，缺少条件可换任务；查资料时需联网',
      safetyNotes: safety + ' 不适或条件不允许时可停止、放弃，不必勉强完成。',
      tags: [outside ? '身边探索' : '室内可做', '低预算', social ? '熟人同行' : '轻量体验'],
      rewards: { ruleVersion: 'mvp-v1', difficulty, xp: reward.xp, attributes },
    }),
  };
}

